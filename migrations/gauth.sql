CREATE TABLE tb_gmail (
	id INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL UNIQUE,
	email TEXT NOT NULL UNIQUE
);

CREATE TABLE tb_role (
	id INTEGER PRIMARY KEY AUTOINCREMENT UNIQUE NOT NULL,
	role TEXT UNIQUE
);

CREATE TABLE tb_org (
	id INTEGER PRIMARY KEY AUTOINCREMENT UNIQUE NOT NULL,
	org TEXT UNIQUE
);

CREATE TABLE tb_gmail_role_org (
	email_id INTEGER,
	role_id INTEGER,
	org_id INTEGER,
	FOREIGN KEY (email_id) REFERENCES tb_gmail (id),
	FOREIGN KEY (role_id) REFERENCES tb_role (id),
	FOREIGN KEY (org_id) REFERENCES tb_org (id)
);
